import { Router } from "express";
import { authenticate, allowRoles } from "../middleware/auth.js";
import { uploadImages } from "../middleware/upload.js";
import { asyncHandler } from "../utils/asyncHandler.js";
import * as c from "../controllers/pickupController.js";
const r = Router(); r.use(authenticate);
r.post("/", allowRoles("household"), uploadImages, asyncHandler(c.createPickup));
r.get("/mine", allowRoles("household"), asyncHandler(c.listHouseholdPickups));
r.get("/stats", allowRoles("household","collector"), asyncHandler(c.pickupStats));
r.get("/available", allowRoles("collector"), asyncHandler(c.listAvailable));
r.get("/assigned", allowRoles("collector"), asyncHandler(c.listMyPickups));
r.post("/:id/accept", allowRoles("collector"), asyncHandler(c.acceptPickup));
r.post("/:id/reject", allowRoles("collector"), asyncHandler(c.rejectPickup));
r.post("/:id/cancel", allowRoles("household"), asyncHandler(c.cancelHouseholdPickup));
r.post("/:id/cancel-assignment", allowRoles("collector"), asyncHandler(c.cancelCollectorAssignment));
r.get("/:id/qr", allowRoles("household"), asyncHandler(c.pickupQr));
r.post("/verify", allowRoles("collector"), asyncHandler(c.verifyQr));
r.post("/complete", allowRoles("collector"), asyncHandler(c.completePickup));
export default r;
