import express from "express";
import cors from "cors";
import cookieParser from "cookie-parser";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import path from "node:path";
import { fileURLToPath } from "node:url";
import authRoutes from "./routes/auth.js";
import pickupRoutes from "./routes/pickups.js";
import walletRoutes from "./routes/wallet.js";
import productRoutes from "./routes/products.js";
import orderRoutes from "./routes/orders.js";
import notificationRoutes from "./routes/notifications.js";
import userRoutes from "./routes/users.js";
import { notFound, errorHandler } from "./middleware/errors.js";
const app = express();
const here = path.dirname(fileURLToPath(import.meta.url));
app.disable("x-powered-by");
app.use(helmet({ crossOriginResourcePolicy: { policy: "cross-origin" } }));
app.use(cors({ origin: process.env.CLIENT_ORIGIN || "http://localhost:5173", credentials: true }));
app.use(express.json({ limit: "1mb" }));
app.use(express.urlencoded({ extended: true, limit: "1mb" }));
app.use(cookieParser());
app.use("/uploads", express.static(path.resolve(process.env.UPLOAD_DIR || "uploads"), { fallthrough: false, maxAge: process.env.NODE_ENV === "production" ? "1d" : 0 }));
app.get("/api/health", (req, res) => res.json({ status: "ok", service: "Green Wallet API" }));
app.use("/api/auth", rateLimit({ windowMs: 15 * 60 * 1000, limit: 60, standardHeaders: true, legacyHeaders: false }), authRoutes);
app.use("/api/pickups", pickupRoutes);
app.use("/api/wallet", walletRoutes);
app.use("/api/products", productRoutes);
app.use("/api/orders", orderRoutes);
app.use("/api/notifications", notificationRoutes);
app.use("/api/users", userRoutes);
app.use(notFound);
app.use(errorHandler);
export default app;
